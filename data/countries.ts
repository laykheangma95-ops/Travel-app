/** Turn 'KH' into 🇰🇭 using regional indicator symbols. */
export function flagEmoji(code: string): string {
  if (code.length !== 2) return '🏳️';
  return String.fromCodePoint(
    ...code.toUpperCase().split('').map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65)
  );
}
